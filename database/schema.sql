CREATE SCHEMA market;
SET search_path = market, pg_catalog;
SET TIME ZONE 'UTC';

CREATE TABLE customers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE
);
CREATE TABLE products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku text NOT NULL UNIQUE,
    current_price numeric(18,2) NOT NULL CHECK (current_price >= 0)
);
CREATE TABLE orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customers,
    created_at timestamptz NOT NULL
);
CREATE TABLE order_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders,
    product_id bigint NOT NULL REFERENCES products,
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(18,2) NOT NULL CHECK (unit_price >= 0)
);
CREATE TABLE payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders,
    status text NOT NULL CHECK (status IN ('FAILED','SUCCESS')),
    external_transaction_id text,
    amount numeric(18,2) NOT NULL CHECK (amount > 0),
    paid_at timestamptz NOT NULL
);
CREATE TABLE refunds (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders,
    amount numeric(18,2) NOT NULL CHECK (amount > 0),
    refunded_at timestamptz NOT NULL
);
CREATE TABLE order_status_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders,
    status text NOT NULL CHECK (status IN ('CREATED','PAID','SHIPPED','DELIVERED','CANCELLED')),
    changed_at timestamptz NOT NULL
);
CREATE TABLE product_price_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES products,
    price numeric(18,2) NOT NULL CHECK (price >= 0),
    valid_from timestamptz NOT NULL
);
